def q(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    coords = {}
    for m in re.finditer(r"^  \('([^']*)', '[^']*', '(?:[^']|'')*', ([-\d.]+), ([-\d.]+)\)", KROTRON.read_text(encoding='utf-8'), re.M):
        coords.setdefault(m.group(1), (float(m.group(2)), float(m.group(3))))
    missing = [p for p in SAME_AS_KROTRON if p not in coords]
    if missing:
        raise SystemExit(f'ไม่พบในข้อมูล Krotron: {missing}')
    rows = [(p, *coords[p]) for p in SAME_AS_KROTRON] + [(p, *ll) for p, ll in GEOCODED.items()]
    values = (',\n  ').join(f'({q(p)}, {lat}, {lng})' for p, lat, lng in rows)
    OUT.write_text(f"""-- นำเข้าจุดเก้าอี้นวด LEMO จากโพสต์ Instagram ของ lemothailand ({len(rows)} จุด ไม่ระบุชั้น)
-- สร้างโดย tools/import_lemo.py  รันซ้ำได้โดยไม่เกิดข้อมูลซ้ำ
insert into locations (geom, place, floor, zone, prices, payments, brand, status, last_verified_at)
select ms_point(v.lat, v.lng), v.place, '-', '', '[]'::jsonb, '{{}}'::text[], 'LEMO', 'verified', now()
from (values
  {values}
) as v(place, lat, lng)
where not exists (
  select 1 from locations l where l.place = v.place and l.brand = 'LEMO'
);
""", encoding='utf-8', newline='\n')
    print(f'{len(rows)} rows -> {OUT}')


if __name__ == '__main__':
    main()
